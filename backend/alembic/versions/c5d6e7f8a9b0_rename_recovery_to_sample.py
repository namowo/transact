def _rename_objects(tables: list[str], old: str, new: str) -> None:
    """Rename constraints and indexes on ``tables`` whose names contain ``old``
    as a whole ``_``-delimited word.

    Constraint names are auto-generated by Postgres (e.g. ``recovery_pkey``,
    ``result_recovery_id_fkey`` and, on PG 18+, ``recovery_id_not_null``), so
    they are looked up instead of hard-coded. Word matching keeps e.g.
    ``sample_sampling_method_id_fkey`` from becoming ``recovery_recoverying_...``
    on downgrade.
    """
    word = re.compile(rf"(^|_){old}(?=_|$)")

    def renamed(name: str) -> str:
        return word.sub(lambda m: m.group(1) + new, name)

    bind = op.get_bind()
    params = {"tables": tables}

    constraints = bind.execute(sa.text("""
        SELECT c.conrelid::regclass::text, c.conname
        FROM pg_constraint c
        JOIN pg_namespace n ON n.oid = c.connamespace
        WHERE n.nspname = current_schema()
          AND c.conrelid::regclass::text = ANY(:tables)
    """), params).all()
    for table, name in constraints:
        if word.search(name):
            op.execute(
                f'ALTER TABLE "{table}" RENAME CONSTRAINT "{name}" '
                f'TO "{renamed(name)}"'
            )

    # Indexes backing constraints (e.g. *_pkey) were renamed along with their
    # constraint above; this catches the plain ones (ix_*_id).
    indexes = bind.execute(sa.text("""
        SELECT indexname FROM pg_indexes
        WHERE schemaname = current_schema() AND tablename = ANY(:tables)
    """), params).scalars().all()
    for name in indexes:
        if word.search(name):
            op.execute(f'ALTER INDEX "{name}" RENAME TO "{renamed(name)}"')


